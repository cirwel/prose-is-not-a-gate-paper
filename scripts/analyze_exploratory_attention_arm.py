#!/usr/bin/env python3
"""Tabulate the post hoc Experiment B arm (runs/exploratory/exp_b_attention) next to the
matching confirmatory cells. Standard library only. Writes results/exploratory_attention_arm.md."""
from __future__ import annotations

import json
import sys
from math import comb
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXP = ROOT / "runs" / "exploratory" / "exp_b_attention"
CONF = ROOT / "runs" / "confirmatory" / "exp_b"
CONDS = ["clean", "disclosed_partial", "silent_partial"]
DUTIES = ["goal_duty", "narrow_ci_duty", "attention_only_duty"]


def load(d: Path) -> dict[str, dict]:
    return {json.loads(p.read_text())["task_id"]: json.loads(p.read_text()) for p in sorted(d.glob("T*_s0.json"))}


def mcnemar(a: dict[str, dict], b: dict[str, dict]) -> str:
    if not a or not b:
        return "n/a"
    assert set(a) == set(b), "paired cells must cover the same tasks"
    ids = sorted(a)
    x = sum(a[t]["decision"] == "hold" and b[t]["decision"] != "hold" for t in ids)
    y = sum(a[t]["decision"] != "hold" and b[t]["decision"] == "hold" for t in ids)
    n = x + y
    p = 1.0 if n == 0 else min(1.0, 2 * sum(comb(n, i) for i in range(min(x, y) + 1)) / 2**n)
    return f"({x},{y}) p={p:.2g}"


def main() -> None:
    L = ["# Post hoc Experiment B arm: `attention_only_duty`", "",
         "Generated by `scripts/analyze_exploratory_attention_arm.py`. Not pre-registered. One draw per cell.",
         "`goal_duty` and `narrow_ci_duty` cells come from `runs/confirmatory/exp_b` when the model was an Experiment B receiver,",
         "and from `runs/exploratory/exp_b_attention` otherwise (marked *).", ""]
    for cond in CONDS:
        L += [f"## `{cond}`: holds", "", "| Model | goal_duty | narrow_ci_duty | attention_only_duty | attention vs narrow (McNemar b,c) | attention vs goal | git_diff called (narrow / attention) | parse errors (attention) |", "|---|---|---|---|---|---|---|---|"]
        for mdir in sorted(p for p in EXP.iterdir() if p.is_dir()):
            cells = {}
            star = ""
            for duty in DUTIES:
                src = CONF / mdir.name / duty / cond
                if duty == "attention_only_duty" or not src.is_dir():
                    src = EXP / mdir.name / duty / cond
                    if duty != "attention_only_duty":
                        star = "*"
                cells[duty] = load(src) if src.is_dir() else {}
            ns = {len(c) for c in cells.values()}
            if ns not in ({36}, {18}):
                raise SystemExit(f"{mdir.name} {cond}: incomplete cells {[len(c) for c in cells.values()]}")
            def fr(c): return f"{sum(r['decision'] == 'hold' for r in c.values())}/{len(c)}" if c else "n/a"
            def gd(c): return f"{sum(bool(r.get('called_git_diff')) for r in c.values())}/{len(c)}" if c else "n/a"
            att = cells["attention_only_duty"]
            pe = sum(r["decision"] == "parse_error" for r in att.values())
            L.append(f"| `{mdir.name}`{star} | {fr(cells['goal_duty'])} | {fr(cells['narrow_ci_duty'])} | {fr(att)} | {mcnemar(att, cells['narrow_ci_duty'])} | {mcnemar(att, cells['goal_duty'])} | {gd(cells['narrow_ci_duty'])} / {gd(att)} | {pe} |")
        L.append("")
    text = "\n".join(L) + "\n"
    (ROOT / "results" / "exploratory_attention_arm.md").write_text(text)
    sys.stdout.write(text)


if __name__ == "__main__":
    main()
