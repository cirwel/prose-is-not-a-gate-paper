#!/usr/bin/env python3
"""Recompute hold counts on clean-labelled patches (Experiments A to C) and the pooled H3a/H3b contrasts
on audited subsets of the 36 tasks.

Reads docs/clean_label_audit.json (per-task verdicts from two independent audit passes)
and the raw confirmatory records. Standard library only. Writes
results/clean_label_sensitivity.md and prints it.

Subsets:
  all            all 36 tasks (the confirmatory analysis)
  not_deviating  drops tasks that both passes marked DEVIATES
  conforming     keeps only tasks that both passes marked CONFORMS
"""
from __future__ import annotations

import json
import sys
from collections import defaultdict
from math import comb
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "runs" / "confirmatory"
CORE5 = ["claude-haiku-5-5", "gpt-6-luna", "gpt-5.4-nano", "gemma4_latest", "nemotron3_33b"]
ALL6 = CORE5[:1] + ["gpt-6.1-sol"] + CORE5[1:]


def sign_p(pos: int, neg: int) -> float:
    n = pos + neg
    if n == 0:
        return 1.0
    k = min(pos, neg)
    return min(1.0, 2 * sum(comb(n, i) for i in range(k + 1)) / 2**n)


def load(rel: str) -> dict[str, bool]:
    """task_id -> held?  (a terminal parse error is a non-hold, as in the confirmatory scorer)"""
    out = {}
    for p in sorted((RUNS / rel).glob("T*_s0.json")):
        d = json.loads(p.read_text())
        out[d["task_id"]] = d.get("decision") == "hold"
    return out


def frac(cell: dict[str, bool], keep: set[str]) -> str:
    ks = [t for t in cell if t in keep]
    return f"{sum(cell[t] for t in ks)}/{len(ks)}"


def pooled_contrast(cells_a: list[dict[str, bool]], cells_b: list[dict[str, bool]], keep: set[str]) -> str:
    pos = neg = zero = 0
    da = db = n = 0
    for t in sorted(keep):
        a = [c[t] for c in cells_a if t in c]
        b = [c[t] for c in cells_b if t in c]
        assert len(a) == len(cells_a) and len(b) == len(cells_b) and len(a) == len(b), f"incomplete coverage for {t}"
        diff = sum(a) / len(a) - sum(b) / len(b)
        da += sum(a); db += sum(b); n += len(a)
        pos += diff > 0; neg += diff < 0; zero += diff == 0
    return f"{da}/{n} vs {db}/{n}; repos +/-/0 = {pos}/{neg}/{zero}; sign p = {sign_p(pos, neg):.3f}"


def main() -> None:
    audit = json.loads((ROOT / "docs" / "clean_label_audit.json").read_text())["tasks"]
    all_ids = {f"T{i:02d}" for i in range(36)}
    assert set(audit) == all_ids
    subsets = {
        "all": all_ids,
        "not_deviating": {t for t, v in audit.items() if v["final"] != "DEVIATES"},
        "conforming": {t for t, v in audit.items() if v["final"] == "CONFORMS"},
    }
    L: list[str] = ["# Clean-label sensitivity analysis", "",
                    "Generated by `scripts/clean_label_sensitivity.py` from `docs/clean_label_audit.json` and `runs/confirmatory/`.", ""]
    L.append("| Subset | Tasks |")
    L.append("|---|---|")
    for k, v in subsets.items():
        L.append(f"| `{k}` | {len(v)} |")
    L.append("")

    # Experiment A
    sigs = ["neutral", "bare_verified", "scoped_verified", "green_ci_badge"]
    a = {(m, s): load(f"exp_a/{m}/{s}/clean") for m in ALL6 for s in sigs}
    L += ["## Experiment A: holds on clean-labelled patches (all four signals pooled)", "",
          "| Model | " + " | ".join(f"`{k}`" for k in subsets) + " |", "|---|" + "---|" * len(subsets)]
    tot = {k: [0, 0] for k in subsets}
    for m in ALL6:
        row = []
        for k, keep in subsets.items():
            h = sum(a[(m, s)][t] for s in sigs for t in a[(m, s)] if t in keep)
            n = sum(1 for s in sigs for t in a[(m, s)] if t in keep)
            tot[k][0] += h; tot[k][1] += n
            row.append(f"{h}/{n} ({h / n:.3f})" if n else "0/0")
        L.append(f"| `{m}` | " + " | ".join(row) + " |")
    L.append("| **all six** | " + " | ".join(f"{h}/{n} ({h / n:.3f})" for h, n in tot.values()) + " |")
    L.append("")
    by_final: dict[str, list[int]] = defaultdict(lambda: [0, 0, 0])
    for (m, s), cell in a.items():
        for t, held in cell.items():
            by_final[audit[t]["final"]][0] += held
            by_final[audit[t]["final"]][1] += 1
    for t, v in audit.items():
        by_final[v["final"]][2] += 1
    L += ["Holds by audit verdict of the task:", "", "| Final verdict | Tasks | Exp A clean holds / records |", "|---|---|---|"]
    for f in ("DEVIATES", "DISPUTED", "AMBIGUOUS", "CONFORMS"):
        if f in by_final:
            h, n, nt = by_final[f]
            L.append(f"| {f} | {nt} | {h}/{n} ({h / n:.3f}) |")
    L.append("")

    # Experiment B
    duties = ["discretion", "goal_duty", "narrow_ci_duty"]
    b = {(m, d): load(f"exp_b/{m}/{d}/clean") for m in ALL6 for d in duties}
    L += ["## Experiment B: holds on clean-labelled patches, Core 5 pooled", "",
          "| Duty | " + " | ".join(f"`{k}`" for k in subsets) + " |", "|---|" + "---|" * len(subsets)]
    for d in duties:
        row = []
        for keep in subsets.values():
            h = sum(b[(m, d)][t] for m in CORE5 for t in b[(m, d)] if t in keep)
            n = sum(1 for m in CORE5 for t in b[(m, d)] if t in keep)
            row.append(f"{h}/{n} ({h / n:.3f})")
        L.append(f"| `{d}` | " + " | ".join(row) + " |")
    L.append("")
    L += ["Per model, `goal_duty` then `narrow_ci_duty`:", "", "| Model | " + " | ".join(f"`{k}`" for k in subsets) + " |", "|---|" + "---|" * len(subsets)]
    for m in ALL6:
        L.append(f"| `{m}` | " + " | ".join(f"{frac(b[(m, 'goal_duty')], keep)} then {frac(b[(m, 'narrow_ci_duty')], keep)}" for keep in subsets.values()) + " |")
    L.append("")

    # Experiment C
    pairings = sorted(p.name for p in (RUNS / "exp_c" / "stage3").iterdir() if p.is_dir())
    arms = ["consensus_brief", "ungated_crux_brief", "gated_crux_brief"]
    c = {(p, arm): load(f"exp_c/stage3/{p}/{arm}/clean") for p in pairings for arm in arms}
    if len(pairings) != 5 or any(set(v) != all_ids for v in c.values()):
        raise SystemExit("Experiment C stage 3: expected five pairings with all 36 clean records per arm")
    L += ["## Experiment C: Stage-3 holds on clean-labelled patches, five pairings pooled", "",
          "| Arm | " + " | ".join(f"`{k}`" for k in subsets) + " |", "|---|" + "---|" * len(subsets)]
    for arm in arms:
        row = []
        for keep in subsets.values():
            h = sum(c[(p, arm)][t] for p in pairings for t in c[(p, arm)] if t in keep)
            n = sum(1 for p in pairings for t in c[(p, arm)] if t in keep)
            row.append(f"{h}/{n} ({h / n:.3f})")
        L.append(f"| `{arm}` | " + " | ".join(row) + " |")
    L.append("")
    L += ["Pooled contrasts on clean (unadjusted exact sign test over repositories):", "", "| Contrast | Subset | Result |", "|---|---|---|"]
    for name, x, y in (("H3a ungated vs consensus", "ungated_crux_brief", "consensus_brief"), ("H3b ungated vs gated", "ungated_crux_brief", "gated_crux_brief")):
        for k, keep in subsets.items():
            L.append(f"| {name} | `{k}` | {pooled_contrast([c[(p, x)] for p in pairings], [c[(p, y)] for p in pairings], keep)} |")
    L.append("")
    text = "\n".join(L) + "\n"
    (ROOT / "results" / "clean_label_sensitivity.md").write_text(text)
    sys.stdout.write(text)


if __name__ == "__main__":
    main()
